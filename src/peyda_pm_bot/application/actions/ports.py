"""Public action persistence and remote API boundaries."""

from typing import Protocol

from peyda_pm_bot.domain.actions.models import (
    ActionDraft,
    ActionRun,
    ActionSpec,
    RemoteComment,
    RemoteIssue,
)
from peyda_pm_bot.domain.agent.models import AgentRequest
from peyda_pm_bot.domain.memory.models import MemoryTurn
from peyda_pm_bot.domain.work.models import BranchProtection, PullSummary


class ActionStore(Protocol):
    async def bind_repository(self, repository: str) -> None: ...
    async def prepare(
        self,
        turn: MemoryTurn,
        key: str,
        spec: ActionSpec,
        base: RemoteIssue | RemoteComment | None,
        action_id: str | None,
        expected_revision: int,
        repository: str,
    ) -> ActionDraft: ...
    async def submit(self, turn: MemoryTurn, action_id: str, revision: int) -> ActionDraft: ...
    async def visible(self, turn: MemoryTurn | None, action_id: str) -> ActionDraft: ...
    async def publish(self, request: AgentRequest) -> None: ...
    async def claim(self, now: float) -> ActionRun | None: ...
    async def current(self, action_id: str) -> ActionRun: ...
    async def result(
        self,
        action_id: str,
        status: str,
        remote: RemoteIssue | RemoteComment | None,
        detail: str = "",
        due: float = 0,
    ) -> None: ...
    async def recover(self) -> None: ...
    async def cancel(self, action_id: str) -> str: ...
    async def retry(self, action_id: str) -> str: ...
    async def invalidate(self, source_ids: tuple[int, ...]) -> None: ...


class Github(Protocol):
    repository: str
    status_labels: dict[str, str]
    bot_login: str

    async def issue(self, number: int) -> RemoteIssue: ...
    async def comment(self, issue_number: int, comment_id: int) -> RemoteComment: ...
    async def issues(self, query: str = "") -> tuple[list[RemoteIssue], bool]: ...
    async def comments(self, issue_number: int) -> tuple[list[RemoteComment], bool]: ...
    async def labels(self) -> tuple[list[str], bool]: ...
    async def assignees(self) -> tuple[list[str], bool]: ...
    async def pull_summaries(self) -> tuple[list[PullSummary], bool]: ...
    async def branch_protection(self) -> BranchProtection: ...
    async def mutate(self, draft: ActionDraft) -> RemoteIssue | RemoteComment: ...
    async def reads(
        self,
        resource: str,
        number: int = 0,
        path: str = "",
        ref: str = "",
        offset: int = 0,
        limit: int = 8000,
    ) -> str: ...
    async def close(self) -> None: ...
